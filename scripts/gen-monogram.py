"""
Builds the MC Bank monogram: the app icons (public/icons*/favicon.svg and
maskable.svg) and src/ui/components/monogram.ts for the in-app logo, all from
one set of shapes so they always match.

The letters are Figtree's own M and C outlines (the app's font) at weight 350,
so they're plain paths and need no font on the phone.

  1. Extract the outlines (needs `pip install fonttools brotli`):
       python3 scripts/gen-monogram.py extract \
         node_modules/@fontsource-variable/figtree/files/figtree-latin-wght-normal.woff2 glyphs.json
  2. Build:  python3 scripts/gen-monogram.py build glyphs.json .
  3. PNGs:   node scripts/gen-icons.mjs public/icons && node scripts/gen-icons.mjs public/icons-dev
"""
import json
import sys

WEIGHT = 350
OVERLAP = 115  # font units the C tucks into the M
CAP = 150  # cap height on the 512 grid
RING_R = 172  # inside Android's maskable safe zone (radius 204.8)
RING_W = 11
BG = "#2f5e48"
DEV_BAND = (
    '<rect y="334" width="512" height="108" fill="#e0b400"/>'
    '<text x="256" y="414" text-anchor="middle" fill="#1b1400" '
    'font-family="Arial, Helvetica, sans-serif" font-size="82" font-weight="800" '
    'letter-spacing="10">DEV</text>'
)


def extract(src, out):
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.ttLib import TTFont
    from fontTools.varLib.instancer import instantiateVariableFont

    font = instantiateVariableFont(TTFont(src), {"wght": WEIGHT})
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    data = {}
    for ch in "MC":
        g = glyphs[cmap[ord(ch)]]
        pen = SVGPathPen(glyphs)
        g.draw(pen)
        bounds = BoundsPen(glyphs)
        g.draw(bounds)
        data[ch] = {"path": pen.getCommands(), "bounds": bounds.bounds}
    json.dump(data, open(out, "w"))


def build(glyph_file, root):
    g = json.load(open(glyph_file))
    m, c = g["M"], g["C"]
    s = CAP / 700  # Figtree's cap height is 700 units
    mw = m["bounds"][2] - m["bounds"][0]
    cw = c["bounds"][2] - c["bounds"][0]
    x0 = 256 - (mw + cw - OVERLAP) * s / 2
    base = 256 + CAP / 2
    mx = x0 - m["bounds"][0] * s
    cx = x0 + (mw - OVERLAP) * s - c["bounds"][0] * s
    mt = f"translate({mx:.2f} {base:.2f}) scale({s:.5f} {-s:.5f})"
    ct = f"translate({cx:.2f} {base:.2f}) scale({s:.5f} {-s:.5f})"
    letters = f'<path transform="{mt}" d="{m["path"]}"/><path transform="{ct}" d="{c["path"]}"/>'

    def svg(full, dev, note):
        corner = "" if full else ' rx="116"'
        body = (
            f'<rect width="512" height="512"{corner} fill="{BG}"/>\n'
            f'  <circle cx="256" cy="256" r="{RING_R}" fill="none" stroke="#ffffff" stroke-width="{RING_W}"/>\n'
            f'  <g fill="#ffffff">{letters}</g>'
        )
        if dev:
            body = (
                f'<defs><clipPath id="tile"><rect width="512" height="512"{corner}/></clipPath></defs>\n'
                f'  <g clip-path="url(#tile)">\n  {body}\n  {DEV_BAND}\n  </g>'
            )
        return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">\n  <!-- {note} -->\n  {body}\n</svg>\n'

    note = "MC Bank monogram. Generated by scripts/gen-monogram.py: edit there, not here."
    for folder, dev in (("icons", False), ("icons-dev", True)):
        extra = " Dev build: with the DEV band." if dev else ""
        open(f"{root}/public/{folder}/favicon.svg", "w").write(svg(False, dev, note + extra))
        open(f"{root}/public/{folder}/maskable.svg", "w").write(
            svg(True, dev, note + extra + " Full-bleed, for Android's icon mask.")
        )
    open(f"{root}/src/ui/components/monogram.ts", "w").write(
        "// Generated by scripts/gen-monogram.py: the MC monogram's shapes on a 512\n"
        "// grid, shared by the in-app logo so it matches the home-screen icon.\n"
        "export const MONOGRAM = {\n"
        f"  background: '{BG}',\n"
        f"  ring: {{ r: {RING_R}, width: {RING_W} }},\n"
        f"  m: {{ transform: '{mt}', d: '{m['path']}' }},\n"
        f"  c: {{ transform: '{ct}', d: '{c['path']}' }},\n"
        "} as const;\n"
    )


if __name__ == "__main__":
    {"extract": extract, "build": build}[sys.argv[1]](*sys.argv[2:])
